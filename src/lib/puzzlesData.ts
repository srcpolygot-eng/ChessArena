/**
 * Deterministic Daily Puzzle selector keyed by local calendar date (YYYY-MM-DD).
 * Guarantees all players receive the exact same Daily Puzzle on a given day.
 */
export function getDailyPuzzle(dateKey: string): ChessPuzzle {
  let hash = 2166136261;
  for (let i = 0; i < dateKey.length; i++) {
    hash ^= dateKey.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const idx = Math.abs(hash) % CHESS_PUZZLES.length;
  return CHESS_PUZZLES[idx];
}

